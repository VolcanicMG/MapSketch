    public static Set<String> names() {
        return ALL.keySet();
    }

    public static boolean has(String name) {
        return ALL.containsKey(base(name));
    }

    private static String base(String name) {
        return name.endsWith("@m") ? name.substring(0, name.length() - 2) : name;
    }

    /** @return true if the pixel at (x, y) of icon {@code name} is ink */
    public static boolean ink(String name, int x, int y) {
        String[] g = ALL.get(base(name));
        if (g == null) return false;
        int c = name.endsWith("@m") ? SIZE - 1 - x : x;
        return g[y].charAt(c) == '#';
    }

    /** @return the raw rows of icon {@code name} (unmirrored), or null */
    public static String[] grid(String name) {
        return ALL.get(base(name));
    }
