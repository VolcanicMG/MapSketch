    private UiIcons() {
    }

    static boolean has(String name) {
        return ALL.containsKey(name);
    }

    /** Draws icon {@code name} centred in the box, in whole-pixel steps so it stays crisp. */
    static void draw(GuiGraphics g, String name, int x, int y, int w, int h, int color) {
        String[] grid = ALL.get(name);
        if (grid == null) return;
        int px = Math.max(1, Math.min(w, h) * 3 / 4 / 12), size = px * 12;
        int ox = x + (w - size) / 2, oy = y + (h - size) / 2;
        for (int r = 0; r < 12; r++)
            for (int c = 0; c < 12; c++)
                if (grid[r].charAt(c) == '#') g.fill(ox + c * px, oy + r * px, ox + (c + 1) * px, oy + (r + 1) * px, color);
    }
